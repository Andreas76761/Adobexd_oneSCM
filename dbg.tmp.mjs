import { chromium } from 'playwright-core';
import { pathToFileURL } from 'node:url';
import { baueVorschau, findeChromium } from './Testing/hilfen/seite.mjs';
const browser = await chromium.launch({ executablePath: findeChromium(), args: ['--no-sandbox','--disable-gpu'] });
const seite = await browser.newPage();
seite.on('pageerror', (e) => console.log('[seitenfehler]', String(e)));
seite.on('console', (m) => m.type()==='error' && console.log('[konsole]', m.text()));
await seite.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.fulfill({status:200,contentType:'text/css',body:''}));
await seite.goto(pathToFileURL(baueVorschau('/home/user/Adobexd_oneSCM/dist/index.html')).href + '#ans=aufnahme');
await seite.waitForSelector('html[data-bereit="ja"]');
await seite.evaluate(() => { document.getElementById('entwurf-labels').open = true; });
await seite.selectOption('#feld-label-sprache', 'de');
await seite.selectOption('#feld-label-rolle_label', 'dealer');
await seite.selectOption('#feld-label-sparte', 'pkw');
await seite.fill('#feld-label-markt', 'Germany');
console.log('Kette:', await seite.locator('#entwurf-label-kette').innerText());
await seite.click('#quelle-beispiel');
await seite.waitForFunction(() => !document.getElementById('ausloesen').disabled);
await seite.fill('#feld-titel', 'Vorlagenliste öffnen');
await seite.fill('#feld-projekt', 'oneSCM Portal');
await seite.selectOption('#feld-kategorie', 'Navigation');
await seite.fill('#feld-begriffe', 'vorlage');
await seite.click('#ausloesen');
await seite.waitForTimeout(400);
const [a] = await seite.evaluate(() => JSON.parse(localStorage.getItem('screenarchiv:eingang')).aufnahmen);
console.log('Aufnahme:', a.id, a.sprache, a.rolle_label, a.sparte, a.markt, '| Kette nachher:', await seite.locator('#entwurf-label-kette').innerText());
// Stellenwahl im Editor
await seite.click('.portal-nav button[data-ansicht="markieren"]');
await seite.selectOption('#markier-wahl', a.id);
await seite.waitForTimeout(500);
await seite.selectOption('#stelle-kapitel', '7');
await seite.waitForTimeout(200);
console.log('Unterkapitel:', (await seite.locator('#stelle-unterkapitel option').allInnerTexts()).slice(0,4));
await seite.selectOption('#stelle-unterkapitel', '7.5');
await seite.waitForTimeout(200);
console.log('Stellen:', (await seite.locator('#stelle-schritt option').allInnerTexts()).slice(0,4));
await seite.selectOption('#stelle-schritt', '7.5.2');
await seite.waitForTimeout(200);
console.log('Stelle:', await seite.locator('#markier-stelle').inputValue(), '|', await seite.locator('#markier-stelle-thema').innerText());
await browser.close();
